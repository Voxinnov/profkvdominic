<p style="margin-top: 1.5em; margin-bottom: 1.5em; padding: 0px; font-family: &quot;Times New Roman&quot;, Times, serif; font-size: 15px;">IV. Area of Operation:&nbsp;&nbsp;&nbsp;&nbsp;&nbsp;&nbsp; All over India</p>
<p style="margin-top: 1.5em; margin-bottom: 1.5em; padding: 0px; font-family: &quot;Times New Roman&quot;, Times, serif; font-size: 15px;">&nbsp;</p>
<p align="center" style="margin-top: 1.5em; margin-bottom: 1.5em; padding: 0px; font-family: &quot;Times New Roman&quot;, Times, serif; font-size: 15px;"><strong style="margin: 0px; padding: 0px;">IV.&nbsp;</strong><strong style="margin: 0px; padding: 0px;">Objectives of the Society</strong></p>
<p style="margin-top: 1.5em; margin-bottom: 1.5em; padding: 0px; font-family: &quot;Times New Roman&quot;, Times, serif; font-size: 15px;">This Guild will be a non-profit-making institution aimed at promoting Indian English literature through the members’ creative and critical writings and by editing and publishing books and journals. Without prejudice to the generality of the above object, the following shall be the aims and objectives of the Guild:</p>
<ol style="margin: 15px 0px 15px 35px; padding: 0px; font-family: &quot;Times New Roman&quot;, Times, serif; font-size: 15px;">
   <li style="margin: 0px; padding: 5px 0px; background: none;">Promote Indian English Literature in general</li>
   <li style="margin: 0px; padding: 5px 0px; background: none;">Publish an international refereed biannual journal entitled&nbsp;<strong style="margin: 0px; padding: 0px;"><em style="margin: 0px; padding: 0px;">Writers Editors Critics&nbsp;</em></strong>for the contributions of the members</li>
   <li style="margin: 0px; padding: 5px 0px; background: none;">Inspire and enlighten the members in creative and critical writing</li>
   <li style="margin: 0px; padding: 5px 0px; background: none;">Assist Ph.D. scholars in thesis writing</li>
   <li style="margin: 0px; padding: 5px 0px; background: none;">Make the members aware of research methodology and the latest documentation style</li>
   <li style="margin: 0px; padding: 5px 0px; background: none;">Conduct annual conferences at various States</li>
   <li style="margin: 0px; padding: 5px 0px; background: none;">Award the best poet, the best novelist, the best short story writer, the best critic, and the best editor every year from among the members</li>
   <li style="margin: 0px; padding: 5px 0px; background: none;">Assist the members in getting their articles published in other journals</li>
   <li style="margin: 0px; padding: 5px 0px; background: none;">Help the members in getting their books published by established publishers</li>
   <li style="margin: 0px; padding: 5px 0px; background: none;">&nbsp;Convince the Minister, HRD, GOI and all the States, Commissioners/Secretaries, HRD, curriculum/syllabus committees of universities and schools to include creative writings of 21<sup style="margin: 0px; padding: 0px;">st</sup>&nbsp;century Indian English writers also in the syllabi.</li>
</ol>
