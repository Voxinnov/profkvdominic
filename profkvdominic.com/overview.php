<p style="margin-top: 1.5em; margin-bottom: 1.5em; padding: 0px; font-family: &quot;Times New Roman&quot;, Times, serif; font-size: 15px;">A literary forum of Indian English writers, entitled&nbsp;<strong style="margin: 0px; padding: 0px;"><em style="margin: 0px; padding: 0px;">Guild of Indian English Writers, Editors and Critics&nbsp;</em>(GIEWEC)</strong>&nbsp;was established on 24 September 2010 at Thodupuzha, Kerala, India. It was registered on 13 October 2010.</p>
