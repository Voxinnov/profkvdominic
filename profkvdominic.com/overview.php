<p style="margin-top: 1.5em; margin-bottom: 1.5em; padding: 0px; font-family: &quot;Times New Roman&quot;, Times, serif; font-size: 15px;">&nbsp;I.&nbsp;Name of the Society: Guild of Indian English Writers, Editors and Critics (GIEWEC)</p>
